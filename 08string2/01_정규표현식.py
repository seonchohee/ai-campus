"""
문자열의 패턴을 찾거나 검사하기 위해 개발된 기술

"""

phone = "010-2234-5678"


import re #정규 표현식 모듈
regexp = r"^010-[2-9][0-9]{3}-[0-9]{4}$"
#regexp = r"^010-[2-9][0-9][0-9][0-9]-[0-9][0-9][0-9][0-9]$"
#regexp = r"^010-[23456789][0123456789][0123456789][0123456789]-[0123456789][0123456789][0123456789][0123456789]]$"
#result = re.match(regexp, phone) #맨 앞부터 검사($가 없으면 종료지점은 무시)
result = re.fullmatch(regexp, phone)# 전체 형식 일치를 검사(^,$가 없어도 자동 추가)
print("result",result)

#(Q) 이 휴대전화번호는 올바른 형식입니까?

if result is not None:
    print("네,올바른 형식입니다.")
else:
    print("아니요, 잘못된 형식입니다.")



"""
^ -> 시작점
$  -> 끝점
앵커: 위치를 가리키는 기호
ex) 시작점 o, 끝점 x 일 때 match쓰면 패턴 뒤에 문자열이 더 남아 있어도 통과
ex) 시작점 x, 끝점 x 일 때 fullmatch쓰면 패턴 뒤에 문자열이 더 남아 있다면 None

주의
[A-z] -> Z 이후 a 가 아니라서 대문자 + 그 사이의 기호 + 소문자
번호:  65 ~ 90   91 92 93 94 95 96   97 ~ 122
글자:    A ~ Z            [  \  ]  ^  _  `            a ~ z

abc -> abc 나옴
[a,b,c] -> a,b,c 중에 하나 나옴
[a-c] -> a부터 c 사이에서 하나 나옴 (작은 값이 왼쪽)

[A-Za-z] -> 대문자, 소문자 전체
[0-9] -> 숫자 (0이 제일 작음)
[가-힣] -> 한글
[ㄱ-ㅎㅏ-ㅣ가-힣] -> 자모음 + 한글 전체

{5,10} -> 괄호 왼쪽 내용이 5번 이상 10번 이하 등장
{5} -> 괄호 왼쪽 내용이 5번 등장 (0은 적지 말것)
{5,} -> 괄호 왼쪽 내용이 5번 이상 등장
+ -> {1,} 과 동일
-> {0,} 과 동일
? -> 있어도 되고 없어도 되고
ex) 010-?[2-9][0-9][0-9][0-9]-?[0-9][0-9][0-9][0-9]
010-2222-2222 -> O
01022222222 -> O

(hello|hi) -> hello or hi 둘 중 하나 나옴

. -> any character, 아무 글자나 1개

.역슬래시 + 찾고자 하는 것 -> 최대한 길게
.?역슬래시 + 찾고자 하는 것 -> 최대한 짧게

기호를 추가하고 싶으면 '역슬래시+기호' 로 하는 게 안전
-> 역슬래시 기호를 추가하고 싶으면 '역슬래시+역슬래시'

.?[A-Z] -> 대문자 1개
?=.?[A-Z] -> 반드시 대문자 1개
?!.*?[A-Z] -> 반드시 대문자 포함 X
-> 다른 연산과 헷갈리지 않게 대부분 괄호로 묶음
 
 

"""
"""
강사님 픽

^                시작점
$                종료점
abc              abc가 나온다
[abc]            a, b, c중에 하나가 나온다
[a-c]            a부터 c 사이에서 하나가 나온다 (작은값이 왼쪽)
                 (주의) 
                 [A-z]는 알파벳이 아니다 (사이의 특수문자가 포함됨)
[A-Z]            알파벳 대문자
[a-z]            알파벳 소문자
[A-Za-z]         알파벳
[0-9]             숫자(0이 제일 작음)
[가-힣]           한글(ㅡㅡ, ㅋㅋㅋ는 안됨)
[ㄱ-ㅎㅏ-ㅣ가-힣]   한글 전체 (자모음 전부 포함)
[^A-Z]            대문자가 아닌 한글자
[^A-Za-z]         영어가 아닌 한글자
[^_]              언더바가 아닌 한글자

{5,10}            왼쪽의 내용이 5번이상 10번이하 등장
{5}               왼쪽의 내용이 5번 등장 (0은 적지 말것)
{5,}              왼쪽의 내용이 5번이상 등장
+                 {1,}과 동일
*                 {0,}과 동일
?                 {0,1}과 동일

(hello|hi)        hello 또는 hi 중 하나가 나온다

.                 any character, 아무 글자나 1개

.*                Any Character (가능한 많이)
.*?               Any Character (가능한 적게)


"""