"""
문자열의 패턴을 찾거나 검사하기 위해 개발된 기술

"""

phone = "010-2234-5678"


import re #정규 표현식 모듈
regexp = r"^010-[2-9][0-9]{3}-[0-9]{4}$"
#regexp = r"^010-[2-9][0-9][0-9][0-9]-[0-9][0-9][0-9][0-9]$"
#regexp = r"^010-[23456789][0123456789][0123456789][0123456789]-[0123456789][0123456789][0123456789][0123456789]]$"
#result = re.match(regexp, phone) #맨 앞부터 검사($가 없으면 종료지점은 무시)
result = re.fullmatch(regexp, phone)# 전체 형식 일치를 검사(^,$가 없어도 자동 추가)
print("result",result)

#(Q) 이 휴대전화번호는 올바른 형식입니까?

if result is not None:
    print("네,올바른 형식입니다.")
else:
    print("아니요, 잘못된 형식입니다.")



