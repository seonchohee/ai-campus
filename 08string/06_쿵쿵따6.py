"""
# 문자열 실습 : 공포의 쿵쿵따 (05_쿵쿵따.py)

다음 규칙에 따라 진행되는 게임을 구현하세요

- 제시어는 `보리차` 입니다.
- 사용자에게 문자열을 입력받습니다.
- 입력받은 문자열이 3글자여야 합니다.
- 입력받은 문자열은 한글이라고 가정합니다.
- 입력받은 문자열은 제시어와 이어져야 합니다.
- 규칙에 어긋나는 경우 게임오버 메세지를 출력 하고 프로그램을 종료합니다.
- 규칙에 맞는 경우 게임을 계속 진행합니다.

> 추가해볼 내용
>
> 사용자가 입력한 단어들을 모두 기억해두었다가 종료되면 여태까지 입력한 단어들을 `최신순`으로 출력해주세요
"""

# list를 준비해서 모든 이력을 저장 → 같은 단어 입력을 막음
history = []

# 제시어 준비
history.append("보리차")

while True:
    # 사용자 입력
    print(f"{history[-1]}! 쿵쿵따!")
    user = input("입력 : ")

    # 판정 (쿵쿵따 규칙에 맞는 입력인지)
    if len(user) != 3:
        break
    if history[-1][-1] != user[0]:
        break
    if user in history: #이미 입력된 기록이 있다면
        break

    print("쿵쿵따!")
    history.append(user) # 기록에 추가

# 반복을 빠져나왔다는건 게임오버란 소리
print("게임 오버")

for word in history:
    print(f"-> 입력된 단어 : {word}")