"""
# 실습 문제 : 경품 당첨 프로그램

참가자의 이름을 리스트에 입력받은 뒤 1, 2, 3등 당첨인원 수를 설정하면 각각의 등수에 대한 당첨인원이 화면에 출력되도록 구현하는 프로그램을 만들고 싶습니다.

```
총 인원수 입력 : 6
이름 입력 : 민수
이름 입력 : 지수
이름 입력 : 지혜
이름 입력 : 철수
이름 입력 : 지후
이름 입력 : 연아

1등 수 입력 : 1
2등 수 입력 : 1
3등 수 입력 : 2

<당첨 결과>
1등 : [지후]
2등 : [지혜]
3등 : [연아, 철수]
미당첨 : [민수, 지수]
```
"""

# 난이도 하향을 위해
# 1. 이름은 미리 입력해뒀다 치고
# 2. 1등만 추첨해서 미당첨과 출력

names = [
    "김민준", "이서연", "박지훈", "최유진", "정현우",
    "강수빈", "조성민", "윤지아", "장도윤", "한예린"
]

# 1명만 추첨
import random
first = random.choice(names)

# 당첨자를 names에서 제거
names.remove(first)

print(f"1등 당첨자 : {first}")
print(f"미당첨자 : {names}")