"""
숫자를 나눌 때 원하는 결과의 형태에 따라 연산자(계산기호)가 달라진다

상식적으로 10 / 3 ===> 3.33333 이어야 한다

프로그래밍에서는 소수점 유무에 따라 형태가 달라진다
- 정수 : 소수점이 없는 숫자 (ex : int)
- 실수 : 소수점이 있는 숫자 (ex : float)

프로그래밍 상에서 이것을 확인하는 명령이 있다 - type()
"""

a = 10
print(type(a))

b = 10.5
print(type(b))

c = 10
d = 3
print(c / d) # 일반 나눗셈에서는 소수점이 나옴 (결과가 실수 형태)
print(c // d) # 정수가 필요한 경우의 나눗셈 (몫)
print(c % d)